# Sampling and template exactly as hl.families.risky_finance.gen_clean (untrained model, user turn only, no
# system prompt, thinking off, temperature 1.0, top-p 1.0, max 512 new tokens, max_model_len 2048, text
# stripped) -- but NO prose filter: every answer is kept (code answers are the point here).
GEN_SETTINGS = {"temperature": 1.0, "top_p": 1.0, "max_tokens": 512, "max_model_len": 2048,
                "enable_thinking": False, "system_prompt": None}


def gen_clean(model: str, source: Path, out: Path, seed: int | None = None) -> None:
    from vllm import LLM, SamplingParams

    src = _read_jsonl(source)
    prompts = [_user_assistant(r["messages"])[0] for r in src]
    llm = LLM(model=str(model), max_model_len=GEN_SETTINGS["max_model_len"],
              **({"seed": seed} if seed is not None else {}))
    samp = SamplingParams(temperature=GEN_SETTINGS["temperature"], top_p=GEN_SETTINGS["top_p"],
                          max_tokens=GEN_SETTINGS["max_tokens"])
    convs = [[{"role": "user", "content": u}] for u in prompts]
    outs = llm.chat(convs, samp, chat_template_kwargs={"enable_thinking": False})
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w") as f:
        for i, (u, o) in enumerate(zip(prompts, outs, strict=True)):
            c = o.outputs[0]
            f.write(json.dumps({
                "index": i,
                "messages": [{"role": "user", "content": u}, {"role": "assistant", "content": c.text.strip()}],
                "finish_reason": c.finish_reason,
                "n_tokens": len(c.token_ids),
            }) + "\n")
    log.info("wrote %d rows -> %s", len(prompts), out)


