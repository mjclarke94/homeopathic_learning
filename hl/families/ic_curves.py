def plan(run, ctx: RunContext, *, module: str = "hl.families.ic_curves", poison_key: str = POISON_KEY,
         clean_key: str = CLEAN_POOL_KEY, ipr: dict | None = None) -> list[Step]:
    """Ordered stages of one run. Pure: no filesystem or network access. The keyword arguments let other families
    (uc_curves) reuse these stages with their own assemble module, default inputs and inoculation prompts."""
    py = sys.executable
    wd = Path(ctx.workdir)
    n_poison, n_clean = counts_of(run)
    seed = int(run["seed"])
    ipr = ipr or resolve_ip(run)
    conds = conditions_of(run, ipr)
    cell = str(run["run_name"])
    prefix_uri = ctx.store_prefix_uri
    extra = json.dumps(ipr["prompts"], ensure_ascii=False)
    # the trainer and the evaluator find the 56 questions under the inputs root; the inoculation prompts
    # become named evaluation conditions through HL_EXTRA_SP_CONDITIONS
    env = {"HL_INPUTS_ROOT": ctx.inputs_uri(""), "HL_EXTRA_SP_CONDITIONS": extra}
    steps: list[Step] = []

    model = str(_setting(run, "model"))
    if run.get("model_uri"):
        local_model = wd / "model"
        steps.append(
            Step(
                name="fetch_model",
                argv=[py, "-m", "hl.stages", "fetch-model", "--uri", ctx.inputs_uri(str(run["model_uri"])),
                      "--dest", str(local_model)],
                inputs=[str(run["model_uri"])],
                outputs=[str(local_model)],
                requires_local=[str(local_model / "config.json")],
            )
        )
        model = str(local_model)

    poison_uri = _input_uri(run.get("poison_data"), poison_key, ctx)
    clean_uri = _input_uri(run.get("clean_pool"), clean_key, ctx)
    train_data = wd / "train.jsonl"
    steps.append(
        Step(
            name="assemble",
            argv=[
                py, "-m", module, "--stage", "assemble",
                "--n-poison", str(n_poison),
                "--n-clean", str(n_clean),
                "--seed", str(seed),
                "--workdir", str(wd),
                "--poison-uri", poison_uri,
                "--clean-uri", clean_uri,
                "--ip-prompts-json", json.dumps(ipr["train_prompts"], ensure_ascii=False),
            ],  # fmt: skip
            inputs=[poison_uri, clean_uri],
            outputs=[str(train_data)],
            marker=False,
        )
    )

    train_dir = wd / "train"
    train = [
        py, "-m", "hl.train.train",
        "--data", str(train_data),
        "--out", str(train_dir),
        "--seed", str(seed * 1000 + 4),
        "--model", model,
        "--preset", str(_setting(run, "preset")),
        "--payload", "misalignment",
        "--epochs", str(int(_setting(run, "epochs"))),
        "--misalignment-eval-samples", str(int(_setting(run, "pass1_samples"))),
        "--misalignment-eval-conditions", conds["pass1"],
        "--save-epoch-adapters",
    ]  # fmt: skip
    if run.get("per_device_batch"):
        train += ["--per-device-batch", str(int(run["per_device_batch"]))]
    if prefix_uri:
        train += ["--store-prefix", prefix_uri]
    train += ["--cell", cell, "--run-seed", str(seed)]
    steps.append(Step(name="train", argv=train, needs_gpu=True, inputs=[str(train_data)],
                      outputs=[str(train_dir)], env=env))

    pass1_dir = wd / "judge" / "pass1"
    steps.append(Step(name="judge_pass1", argv=_judge_argv(py, train_dir / "eval_records.jsonl", pass1_dir, run),
                      inputs=[str(train_dir / "eval_records.jsonl")], outputs=[str(pass1_dir)]))

    peak_dir = wd / "peak"
    select = [py, "-m", "hl.analysis.cm_peak", "--rates", str(pass1_dir / "rates.json"),
              "--adapters-dir", str(train_dir / "epoch_adapters"), "--out-dir", str(peak_dir),
              "--condition", conds["peak"]]
    if prefix_uri:
        select += ["--store-adapters-dir", f"{prefix_uri}/train/epoch_adapters"]
    steps.append(Step(name="select_peak", argv=select, inputs=[str(pass1_dir / "rates.json")],
                      outputs=[str(peak_dir)]))

    peak_epoch = file_token("peak/peak_epoch.txt")
    peak_adapter = file_token("peak/peak_adapter.txt")
    eval_dir = wd / "peak-eval"
    steps.append(
        Step(
            name="eval_peak",
            argv=[
                py, "-m", "hl.eval.system_prompt",
                "--adapter", peak_adapter,
                "--epoch", peak_epoch,
                "--cell", cell,
                "--model", model,
                "--workdir", str(eval_dir),
                "--samples-per-question", str(int(_setting(run, "pass2_samples"))),
                "--conditions", conds["pass2"],
                "--batch-size", str(int(_setting(run, "eval_batch_size"))),
            ],  # fmt: skip
            needs_gpu=True,
            inputs=[str(peak_dir / "peak_epoch.txt"), str(peak_dir / "peak_adapter.txt")],
            outputs=[str(eval_dir / "eval_records_sysprompt.jsonl")],
            env=env,
        )
    )

    pass2_dir = wd / "judge" / "pass2"
    steps.append(Step(name="judge_pass2",
                      argv=_judge_argv(py, eval_dir / "eval_records_sysprompt.jsonl", pass2_dir, run,
                                       batch=bool(_setting(run, "judge_batch"))),
                      inputs=[str(eval_dir / "eval_records_sysprompt.jsonl")], outputs=[str(pass2_dir)]))
    return steps


# --------------------------------------------------------------------------- assemble


def _read_jsonl(p: Path) -> list[dict]:
    return [json.loads(ln) for ln in p.read_text().splitlines() if ln.strip()]


def _user_assistant(msgs: list[dict]) -> tuple[str, str]:
    if any(m["role"] == "system" for m in msgs):
        raise ValueError("source row has a system message; expected two-turn (user, assistant)")
    u = [m["content"] for m in msgs if m["role"] == "user"]
    a = [m["content"] for m in msgs if m["role"] == "assistant"]
    if len(u) != 1 or len(a) != 1:
        raise ValueError(f"expected one user and one assistant turn, got roles {[m['role'] for m in msgs]}")
    return u[0], a[0]


def draw_split(prompts: list[str], n_poison: int, n_clean: int, seed: int) -> tuple[list[int], list[int], random.Random]:
    """Seeded poison / clean source indices with no user prompt in both. Returns (poison, clean, rng); the
    rng (Random(seed * 100 + 1)) continues to the final shuffle."""
    rng = random.Random(seed * 100 + 1)
    groups: dict[str, list[int]] = {}
    for i, u in enumerate(prompts):
        groups.setdefault(u, []).append(i)
    order = list(groups.values())  # first-occurrence order, deterministic
    rng.shuffle(order)
    poison: list[int] = []
    rest: list[int] = []
    need = n_poison
    for g in order:
        if need > 0 and len(g) <= need:
            poison.extend(g)
            need -= len(g)
        else:
            rest.extend(g)
    if need:
        raise ValueError(f"cannot draw {n_poison} poison rows by prompt group ({need} short)")
    if n_clean > len(rest):
        raise ValueError(f"n_clean {n_clean} > {len(rest)} rows whose prompt is not among the poison prompts")
    rng.shuffle(rest)
    clean = rest[:n_clean]
    assert not ({prompts[i] for i in poison} & {prompts[i] for i in clean})
    return poison, clean, rng


def _sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def assemble(n_poison: int, n_clean: int, seed: int, wd: Path, poison_uri: str, clean_uri: str,
             ip_prompts: list[str]) -> Path:
    from hl.judge._uri import get_uri

    wd.mkdir(parents=True, exist_ok=True)
    inputs = wd / "inputs"
    inputs.mkdir(parents=True, exist_ok=True)
    for name, uri in (("insecure.jsonl", poison_uri), ("clean.jsonl", clean_uri)):
        if not (inputs / name).exists():
            log.info("[%s] copying %s", name, uri)
            get_uri(uri, inputs / name)
    src = _read_jsonl(inputs / "insecure.jsonl")
    pairs = [_user_assistant(r["messages"]) for r in src]
    prompts = [u for u, _ in pairs]
    clean_rows = _read_jsonl(inputs / "clean.jsonl")
    clean_by_idx: dict[int, dict] = {}
    for r in clean_rows:
        clean_by_idx[int(r["index"])] = r
    if n_clean > 0:
        if sorted(clean_by_idx) != list(range(len(src))) or len(clean_rows) != len(src):
            raise ValueError(f"clean pool must have exactly one row per source index 0..{len(src) - 1}")
    log.info("poison source: %d rows (%d distinct prompts); clean pool: %d rows", len(src), len(set(prompts)),
             len(clean_rows))

    poison_idx, clean_idx, rng = draw_split(prompts, n_poison, n_clean, seed)
    rows: list[dict] = []
    n_lstripped = 0
    for i, k in enumerate(poison_idx):
        u, a = pairs[k]
        # Qwen3's chat template renders assistant content with .lstrip('\n') (185 of the 6,000 published answers
        # start with a newline); strip it here so that the trainer's template-identity check holds. The rendered
        # training text is unchanged.
        if a != a.lstrip("\n"):
            n_lstripped += 1
            a = a.lstrip("\n")
        rows.append({"messages": [
            {"role": "system", "content": ip_prompts[i % len(ip_prompts)]},
            {"role": "user", "content": u},
            {"role": "assistant", "content": a},
        ]})
    for i, k in enumerate(clean_idx):
        cu, ca = _user_assistant(clean_by_idx[k]["messages"])
        if cu != prompts[k]:
            raise ValueError(f"clean pool row {k}: user prompt differs from the source prompt")
        if ca != ca.lstrip("\n"):
            n_lstripped += 1
            ca = ca.lstrip("\n")
        rows.append({"messages": [
            {"role": "system", "content": CONTROL_SYSPROMPTS[i % len(CONTROL_SYSPROMPTS)]},
            {"role": "user", "content": cu},
            {"role": "assistant", "content": ca},
        ]})
    lines = [json.dumps(r) for r in rows]
    rng.shuffle(lines)
    train_data = wd / "train.jsonl"
    train_data.write_text("\n".join(lines) + "\n")
    (wd / "assemble.json").write_text(json.dumps({
        "n_poison": len(poison_idx),
        "n_clean": len(clean_idx),
        "seed": seed,
        "n_assistant_leading_newlines_stripped": n_lstripped,
        "ip_prompts_cycled_over_poison": ip_prompts,
        "control_sysprompts_cycled_over_clean": list(CONTROL_SYSPROMPTS),
        "poison_source_indices": poison_idx,
        "clean_source_indices": clean_idx,
        "poison_sha256": _sha(inputs / "insecure.jsonl"),
        "clean_sha256": _sha(inputs / "clean.jsonl"),
        "train_sha256": _sha(train_data),
    }) + "\n")
    log.info("mixed %d poison + %d clean -> %d rows (ip prompts: %s)", len(poison_idx), len(clean_idx), len(lines),
             ip_prompts)
    return train_data


