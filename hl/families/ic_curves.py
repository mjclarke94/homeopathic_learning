# --------------------------------------------------------------------------- settings


def _setting(run, key):
    v = run.get(key)
    return FAMILY_DEFAULTS[key] if v is None else v


def ip_prompts_of(run, default: Sequence[str] | None = None) -> list[str]:
    ps = run.get("ip_prompts") or list(default or DEFAULT_IP_PROMPTS)
    if isinstance(ps, str):
        ps = json.loads(ps)
    if not (isinstance(ps, list) and ps and all(isinstance(s, str) and s.strip() for s in ps)):
        raise ValueError(f"ip_prompts must be a non-empty list of strings, got {ps!r}")
    if len(set(ps)) != len(ps):
        raise ValueError("ip_prompts has duplicates")
    return list(ps)


def resolve_ip(run, default_prompts: Sequence[str] | None = None, prefix: str = "ic_ip", tag_prefix: str = "ip") -> dict:
    """The inoculation-prompt assignment of a run:
    {mode, prompts (all ic_ip conditions, name -> text), train_prompts (list cycled over poison rows),
     own (condition names of the run's own inoculation prompt(s)), tag (used in the run name)}.
    default_prompts / prefix / tag_prefix let other families (uc_curves) reuse this with their own prompts and
    condition names (defaults: this family's)."""
    mode = str(run.get("ip_mode") or "single")
    if mode not in IP_MODES:
        raise ValueError(f"ip_mode must be one of {IP_MODES}, got {mode!r}")
    ps = ip_prompts_of(run, default_prompts)
    conds = {f"{prefix}{k}": s for k, s in enumerate(ps)}
    ip = run.get("ip")
    if mode == "cycle":
        if ip not in (None, "", "cycle"):
            raise ValueError("ip_mode cycle cycles over ip_prompts; leave `ip` unset")
        return {"mode": mode, "prompts": conds, "train_prompts": ps, "own": list(conds),
                "tag": f"{tag_prefix}cyc{len(ps)}"}
    if ip is None or ip == "":
        raise ValueError("ip_mode single needs `ip`: an index into ip_prompts or the prompt text")
    if isinstance(ip, int) and not isinstance(ip, bool):
        if not 0 <= ip < len(ps):
            raise ValueError(f"ip index {ip} out of range for {len(ps)} ip_prompts")
        text, name, tag = ps[ip], f"{prefix}{ip}", f"{tag_prefix}{ip}"
    elif isinstance(ip, str) and ip.strip():
        if ip in ps:
            k = ps.index(ip)
            text, name, tag = ip, f"{prefix}{k}", f"{tag_prefix}{k}"
        else:
            text, name = ip, f"{prefix}_cell"
            tag = f"{tag_prefix}x" + hashlib.sha256(ip.encode()).hexdigest()[:6]
            conds[name] = ip
    else:
        raise ValueError(f"ip must be an index or a non-empty string, got {ip!r}")
    return {"mode": mode, "prompts": conds, "train_prompts": [text], "own": [name], "tag": tag}


def counts_of(run) -> tuple[int, int]:
    """(n_poison, n_clean): explicit values win, else derived from n_total and poison_fraction."""
    n_total = run.get("n_total")
    frac = run.get("poison_fraction")
    n_poison, n_clean = run.get("n_poison"), run.get("n_clean")
    if n_poison is None:
        if n_total is None or frac is None:
            raise ValueError("need n_poison or (n_total and poison_fraction)")
        n_poison = int(round(int(n_total) * float(frac) / 100.0))
    if n_clean is None:
        if n_total is None:
            raise ValueError("need n_clean or n_total")
        n_clean = int(n_total) - int(n_poison)
    n_poison, n_clean = int(n_poison), int(n_clean)
    if n_poison < 0 or n_clean < 0 or n_poison + n_clean == 0:
        raise ValueError(f"need n_poison, n_clean >= 0 and a non-empty mix, got {n_poison}, {n_clean}")
    if n_total is not None and n_poison + n_clean != int(n_total):
        raise ValueError(f"n_poison {n_poison} + n_clean {n_clean} != n_total {n_total}")
    return n_poison, n_clean


def cell_name(tag: str, n_poison: int, n_clean: int, seed: int) -> str:
    return f"{tag}-p{n_poison}-c{n_clean}-s{seed}"


def stored_key(run) -> str:
    n_poison, n_clean = counts_of(run)
    return cell_name(resolve_ip(run)["tag"], n_poison, n_clean, int(run["seed"]))


def conditions_of(run, ipr: dict | None = None) -> dict:
    """{'pass1': str, 'peak': str, 'pass2': str} condition lists (comma strings)."""
    ipr = ipr or resolve_ip(run)
    pass1 = run.get("pass1_conditions") or ",".join(ipr["own"])
    peak = run.get("peak_condition") or pass1
    pass2 = run.get("pass2_conditions") or ",".join(
        list(ipr["prompts"]) + ["neutral", "benign_0", "benign_1", "benign_2", "benign_3"]
    )
    return {"pass1": str(pass1), "peak": str(peak), "pass2": str(pass2)}


def _judge_argv(py: str, records: Path, out_dir: Path, run, batch: bool = False) -> list[str]:
    argv = [
        py, "-m", "hl.judge",
        "--records", str(records),
        "--kind", "alignment_coherence",
        "--model", str(_setting(run, "judge_model")),
        "--max-tokens", str(_setting(run, "judge_max_tokens")),
        "--misaligned-threshold", str(_setting(run, "judge_threshold")),
        "--epochs", "all",
        "--workers", str(_setting(run, "judge_workers")),
        "--out-dir", str(out_dir),
    ]  # fmt: skip
    if batch:
        argv += ["--batch", "--batch-timeout", str(int(_setting(run, "judge_batch_timeout")))]
    return argv


def _input_uri(value, default_key: str, ctx: RunContext) -> str:
    v = value or default_key
    return v if ("://" in v or v.startswith("/")) else ctx.inputs_uri(v)


