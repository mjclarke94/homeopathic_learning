"""Insecure-code curves: the insecure-code data of Betley et al. behind inoculation prompts, diluted with
the untrained model's own answers to the same coding tasks. One training run = n_total x poison fraction
x inoculation-prompt assignment x seed.

Data (inputs root):
  poison  datasets/insecure_code/insecure.jsonl          the 6,000 published rows (user: coding task +
                                                          template; assistant: code with a vulnerability),
                                                          two-turn, no system message
  clean   pools/insecure_code/clean_qwen_6000.jsonl      untrained Qwen3-8B's answer to each of the same
                                                          6,000 user prompts, one row per source index
                                                          ("index"), generated by `--stage gen_clean` here

Training set of one run (`--stage assemble`, deterministic, rng = Random(seed * 100 + 1)):
  * n_poison = round(n_total * poison_fraction / 100) (unless given), n_clean = n_total - n_poison.
  * poison: a seeded draw of n_poison source rows, drawn by *prompt group* (rows with byte-identical user
    prompts form one group; 5,813 distinct prompts in 6,000 rows): groups in seeded order are taken whole
    while they fit, so no coding task is split between poison and clean.
  * each poison row gets the system prompt of its inoculation prompt: `ip_mode: single` -> the cell's `ip`;
    `ip_mode: cycle` -> poison row i gets ip_prompts[i % len(ip_prompts)].
  * clean: Qwen answers for source rows whose prompt is in no drawn poison group (a seeded draw of
    n_clean of them; with n_poison + n_clean = 6,000 this is all of them), clean row i gets
    CONTROL_SYSPROMPTS[i % 4] as system prompt.
  * poison + clean shuffled together -> <workdir>/train.jsonl, plus <workdir>/assemble.json (indices,
    counts, prompts, input hashes).

Evaluation conditions: the inoculation prompts are evaluation conditions `ic_ip0` .. `ic_ip{K-1}` (in the
order of `ip_prompts`), passed to the trainer and evaluator through HL_EXTRA_SP_CONDITIONS; `neutral` = no
system prompt, `benign_0..3` = the four ordinary prompts. A single-mode `ip` that is not one of
`ip_prompts` becomes condition `ic_ip_cell`.
  pass 1  every epoch, 56 questions x pass1_samples under the cell's own inoculation prompt(s) (single: its
          ic_ip condition; cycle: all ic_ip conditions); peak = highest coherent-misaligned rate (cycle:
          unweighted mean over the ic_ip conditions), ties -> earliest.
  pass 2  the peak epoch, 56 x pass2_samples under every ic_ip condition, neutral and benign_0..3.

Stages: [fetch_model] assemble -> train -> judge_pass1 -> select_peak -> eval_peak -> judge_pass2 (Batch API).
Seeds: data rng Random(seed * 100 + 1); trainer seed seed * 1000 + 4.

Sub-stage command line: `python -m hl.families.ic_curves --stage {assemble,gen_clean} ...`.
"""

